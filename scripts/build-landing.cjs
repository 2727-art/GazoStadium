const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const postcss = require('../functions/node_modules/postcss');
const root = path.resolve(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const check = process.argv.includes('--check');
const write = (f, content) => {
  if (check) { if (read(f).replace(/\r\n/g, '\n') !== content.replace(/\r\n/g, '\n')) throw new Error(`${f} needs: node scripts/build-landing.cjs`); }
  else fs.writeFileSync(path.join(root, f), content);
};
const app = read('app.js');
const source = app.slice(app.indexOf('  function renderLanding()'), app.indexOf('  function renderLandingScreen()'));
const html = vm.runInNewContext(source + '; renderLanding()', { window: { localStorage: { getItem: () => null } } }).replace(/^ +$/gm, '');
const index = read('index.html').replace(/(<main id="app" tabindex="-1">)[\s\S]*?(<\/main>)/, (_, a, b) => a + html + b);
write('index.html', index);
const classes = new Set([...index.matchAll(/class="([^"]*)"/g)].flatMap(m => m[1].split(/\s+/)));
for (const name of ['loader','show','is-visible','is-busy','gameover-card','loading-overlay','loading-card','loading-spinner','vl-ranch-resume','vl-ranch-resume-mark','vl-ranch-resume-text','vl-ranch-resume-go']) classes.add(name);
const ids = new Set([...index.matchAll(/id="([^"]*)"/g)].map(m => m[1]));
function needed(selector) {
  return [...selector.matchAll(/\.([a-zA-Z_][\w-]*)|#([a-zA-Z_][\w-]*)/g)].every(m => m[1] ? classes.has(m[1]) : ids.has(m[2]));
}
const css = postcss.parse(read('styles.css'));
css.walkRules(rule => {
  if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  const selectors = rule.selectors.filter(needed);
  if (selectors.length) rule.selectors = selectors;
  else rule.remove();
});
css.walkComments(comment => comment.remove());
css.walkAtRules(rule => { if (rule.nodes && !rule.nodes.length) rule.remove(); });
write('landing-base.css', '/* Generated by scripts/build-landing.cjs. Edit styles.css, then regenerate. */\n' + css.toString().trim() + '\n');
console.log(`Landing: ${Buffer.byteLength(html)} HTML bytes; ${Buffer.byteLength(css.toString())} CSS bytes`);
