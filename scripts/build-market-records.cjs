const fs = require('fs');
process.chdir(require('node:path').resolve(__dirname, '..'));
const acorn = require('../functions/node_modules/acorn');
const source = fs.readFileSync('market.js','utf8');
const ast = acorn.parse(source,{ecmaVersion:'latest',sourceType:'module'});
const nodes = new Map();
for(const node of ast.body){
 if(node.type==='FunctionDeclaration') nodes.set(node.id.name,node);
 if(node.type==='VariableDeclaration') for(const d of node.declarations) if(d.id.type==='Identifier')nodes.set(d.id.name,node);
}
// Retired transaction code is not an entry point. Copy only the existing record
// renderers and their pure helpers so old certificates retain exactly their labels.
const shell = fs.readFileSync('scripts/market-records-shell.js','utf8');
const ownAst = acorn.parse(shell,{ecmaVersion:'latest',sourceType:'module'});
const own = new Set();
for(const node of ownAst.body){
 if(node.type==='FunctionDeclaration')own.add(node.id.name);
 if(node.type==='VariableDeclaration')for(const d of node.declarations)own.add(d.id.name);
 if(node.type==='ImportDeclaration')for(const s of node.specifiers)own.add(s.local.name);
}
const selected = new Set();
function visit(node,cb){ if(!node||typeof node!=='object')return; if(node.type==='Identifier')cb(node.name); for(const [key,v] of Object.entries(node))if(key!=='start'&&key!=='end'){if(Array.isArray(v))v.forEach(n=>visit(n,cb));else if(v&&typeof v==='object')visit(v,cb);} }
function add(name){if(own.has(name)||selected.has(name)||!nodes.has(name))return; selected.add(name);visit(nodes.get(name),add);}
for(const name of ['renderRankings','renderCertificates','openRankings','openCertificates','selectMarketRankingPeriod','saveMarketRankingPublicProfile','updateMarketProfilePreview','updateMarketXHandleInput','normalizeMarketMonthlyAchievements']) add(name);
const picked = [...new Set([...selected].map(n=>nodes.get(n)))].sort((a,b)=>a.start-b.start).map(n=>source.slice(n.start,n.end)).join('\n\n');
const output = '// Generated by scripts/build-market-records.cjs from the historical market renderers.\n' + shell + '\n' + picked + '\n';
if(process.argv.includes('--check')){if(fs.readFileSync('market-records.js','utf8')!==output)throw Error('Run node scripts/build-market-records.cjs');}
else fs.writeFileSync('market-records.js',output);
console.log(`Records: ${Buffer.byteLength(output)} bytes; ${selected.size} declarations`);

