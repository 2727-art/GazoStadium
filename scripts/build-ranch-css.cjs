// Keep the shared styles used by the ranch; the full shared sheet remains available to other modes.
const fs = require("node:fs");
const path = require("node:path");
const postcss = require("../functions/node_modules/postcss");
const root = path.resolve(__dirname, "..");
const read = file => fs.readFileSync(path.join(root, file), "utf8");
const html = read("index.html");
const chrome = html.slice(0, html.indexOf('<main id="app"')) + html.slice(html.indexOf('</main>') + 7, html.indexOf('<script type="application/json"'));
const source = [chrome, ...["tribute.js", "tribute-core.mjs", "tribute-deco.mjs", "tribute-share.mjs", "achievements.js", "player-safety.js"].map(read)].join("\n");
const tokens = new Set(source.match(/[a-zA-Z_][\w-]*/g));
for (const token of ["app", "screen", "button", "button-primary", "button-secondary", "button-ghost", "button-small", "show", "is-visible"]) tokens.add(token);
const css = postcss.parse(read("styles.css"));
css.walkRules(rule => {
  if (rule.parent.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  const selectors = rule.selectors.filter(selector => [...selector.matchAll(/\.([a-zA-Z_][\w-]*)|#([a-zA-Z_][\w-]*)/g)]
    .every(match => tokens.has(match[1] || match[2]) || /^is-/.test(match[1] || "")));
  if (selectors.length) rule.selectors = selectors;
  else rule.remove();
});
css.walkComments(comment => comment.remove());
css.walkAtRules(rule => { if (rule.nodes && !rule.nodes.length) rule.remove(); });
const output = "/* Generated by scripts/build-ranch-css.cjs. Edit styles.css, then regenerate. */\n" + css.toString().trim() + "\n";
if (process.argv.includes("--check")) {
  if (read("ranch-base.css").replace(/\r\n/g, "\n") !== output.replace(/\r\n/g, "\n")) throw Error("ranch-base.css needs regeneration");
} else fs.writeFileSync(path.join(root, "ranch-base.css"), output);
console.log(`Ranch shared CSS: ${Buffer.byteLength(output)} bytes`);
